# Analysis helpers. Feel free to edit the REVIEW_TERMS list for your own context.
import hashlib, json, re, zipfile
from collections import Counter
from datetime import datetime, timezone
from xml.etree import ElementTree as ET
import pandas as pd
from pypdf import PdfReader

NS = {'cp':'http://schemas.openxmlformats.org/package/2006/metadata/core-properties',
      'dc':'http://purl.org/dc/elements/1.1/',
      'dcterms':'http://purl.org/dc/terms/',
      'ep':'http://schemas.openxmlformats.org/officeDocument/2006/extended-properties',
      'r':'http://schemas.openxmlformats.org/officeDocument/2006/relationships',
      'main':'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}

OOXML = {'.xlsx', '.xlsm', '.docx', '.pptx'}
REVIEW_TERMS = ['openpyxl', 'xlsxwriter', 'python-docx', 'python-pptx', 'libreoffice', 'openoffice', 'google', 'gspread', 'pandas', 'reportlab', 'weasyprint', 'wkhtmltopdf', 'gpt', 'openai', 'claude', 'gemini', 'copilot']

def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()

def clean(value):
    if value is None: return ''
    return re.sub(r'\s+', ' ', str(value)).strip()

def read_xml(zf, name):
    try: return ET.fromstring(zf.read(name))
    except (KeyError, ET.ParseError): return None

def text_at(root, query):
    node = root.find(query, NS) if root is not None else None
    return clean(node.text) if node is not None else ''

def ooxml_info(path):
    meta, evidence, details = {}, [], {}
    with zipfile.ZipFile(path) as zf:
        names = zf.namelist()
        core = read_xml(zf, 'docProps/core.xml')
        app = read_xml(zf, 'docProps/app.xml')
        custom = read_xml(zf, 'docProps/custom.xml')

        fields = {'creator':'dc:creator','last_modified_by':'cp:lastModifiedBy','created':'dcterms:created','modified':'dcterms:modified','title':'dc:title','subject':'dc:subject','description':'dc:description','keywords':'cp:keywords','category':'cp:category'}
        meta.update({key:text_at(core, xpath) for key,xpath in fields.items()})

        meta['application'] = text_at(app, 'ep:Application')
        meta['app_version'] = text_at(app, 'ep:AppVersion')
        meta['company'] = text_at(app, 'ep:Company')
        meta['manager'] = text_at(app, 'ep:Manager')
        meta['total_edit_time'] = text_at(app, 'ep:TotalTime')
        meta['shared_doc'] = text_at(app, 'ep:SharedDoc')

        if custom is not None:
            details['custom_properties'] = ' | '.join(clean(x.text) for x in custom.iter() if x.text)[:3000]

        blob = (' '.join([zf.read(n).decode('utf-8', 'ignore') for n in names if n.endswith(('.xml','.rels'))])).lower()
        for term in REVIEW_TERMS:
            if term in blob:
                evidence.append(f'Package contains: {term}')

        # Format-specific structural observations
        if path.suffix.lower() in {'.xlsx','.xlsm'}:
            # Get sheets and visibility metadata
            wb_xml = read_xml(zf, 'xl/workbook.xml')
            sheets_list = []
            hidden_sheets = []
            very_hidden_sheets = []
            if wb_xml is not None:
                sheets_node = wb_xml.find('main:sheets', NS)
                if sheets_node is not None:
                    for s in sheets_node.findall('main:sheet', NS):
                        name = s.get('name', '')
                        state = s.get('state', 'visible')
                        sheets_list.append(name)
                        if state == 'hidden':
                            hidden_sheets.append(name)
                        elif state == 'veryHidden':
                            very_hidden_sheets.append(name)

            details['sheets'] = ', '.join(sheets_list)
            details['hidden_sheets'] = ', '.join(hidden_sheets) if hidden_sheets else 'None'
            details['very_hidden_sheets'] = ', '.join(very_hidden_sheets) if very_hidden_sheets else 'None'
            details['hidden_parts'] = ', '.join(n for n in names if '/hidden' in n.lower())
            details['has_macros'] = 'Yes' if any(n.lower().endswith('vbaproject.bin') for n in names) else 'No'
            details['has_external_links'] = 'Yes' if any('externalLink' in n for n in names) else 'No'
            details['formula_cells'] = sum(zf.read(n).count(b'<f') for n in names if n.startswith('xl/worksheets/') and n.endswith('.xml'))
            details['tables'] = sum(1 for n in names if n.startswith('xl/tables/'))
            details['charts'] = sum(1 for n in names if n.startswith('xl/charts/'))

        elif path.suffix.lower() == '.docx':
            details['comments'] = sum(1 for n in names if 'comments' in n.lower())
            details['tracked_changes'] = 'Yes' if b'<w:ins' in zf.read('word/document.xml') or b'<w:del' in zf.read('word/document.xml') else 'No'

        elif path.suffix.lower() == '.pptx':
            details['slides'] = sum(1 for n in names if re.match(r'ppt/slides/slide\d+\.xml$', n))

        # Structural Signature
        parts = []
        for n in sorted(names):
            if n.startswith('docProps/') or n.endswith('.rels') or n == '[Content_Types].xml': continue
            if n.endswith('.xml'):
                raw = zf.read(n).decode('utf-8','ignore')
                raw = re.sub(r'\br:id="[^"]+"', '', raw)
                raw = re.sub(r'<dcterms:(created|modified)[^>]*>.*?</dcterms:(created|modified)>', '', raw)
                parts.append(n + ':' + hashlib.sha256(raw.encode()).hexdigest())
        details['structural_signature'] = hashlib.sha256('\n'.join(parts).encode()).hexdigest() if parts else ''
    return meta, evidence, details

def pdf_info(path):
    meta, evidence, details = {}, [], {}
    reader = PdfReader(str(path))
    raw = reader.metadata or {}
    keymap = {'/Author':'creator','/Creator':'application','/Producer':'producer','/Title':'title','/Subject':'subject','/Keywords':'keywords','/CreationDate':'created','/ModDate':'modified'}
    meta = {new: clean(raw.get(old, '')) for old,new in keymap.items()}
    details['pages'] = len(reader.pages)
    details['encrypted'] = 'Yes' if reader.is_encrypted else 'No'
    blob = ' '.join(clean(v) for v in raw.values()).lower()
    for term in REVIEW_TERMS:
        if term in blob:
            evidence.append(f'PDF metadata contains: {term}')
    details['structural_signature'] = hashlib.sha256((str(len(reader.pages)) + str(sorted(raw.keys()))).encode()).hexdigest()
    return meta, evidence, details

def analyze(path):
    digest = sha256(path)
    base = {'relative_path':str(path.relative_to(EXTRACT)), 'file_name':path.name, 'extension':path.suffix.lower(), 'bytes':path.stat().st_size, 'sha256':digest}
    try:
        meta, evidence, details = ooxml_info(path) if path.suffix.lower() in OOXML else pdf_info(path)
        flags = []
        if not meta.get('creator'): flags.append('Creator metadata missing')
        if not meta.get('application') and path.suffix.lower() in OOXML: flags.append('Application metadata missing')
        if evidence: flags.extend(evidence)
        base.update(meta); base.update(details); base['evidence'] = ' | '.join(evidence); base['review_flags'] = ' | '.join(flags); base['analysis_error'] = ''
    except Exception as exc:
        base.update({'evidence':'','review_flags':'Could not fully parse','analysis_error':f'{type(exc).__name__}: {exc}'})
    return base

