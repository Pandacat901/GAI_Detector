"""## How to read the report

- **All Submissions** retains every Canvas upload, including team duplicates.
- **Unique Files** is the main review sheet: each SHA-256-exact workbook/document appears once.
- **Exact Duplicate Groups** lists the Canvas paths that contained identical file bytes. That is expected for a team submission.
- **Similar Structure Leads** identifies OOXML files that share a structural signature after volatile metadata is excluded. Treat this only as a lead: common templates and instructor-provided starter files can naturally cluster.
- **Review Flags** preserves the observed basis for any flag. Software names or incomplete metadata can arise from legitimate tools, conversions, accessibility workflows, or resaving.

For best interpretation, compare a flagged submission with the assignment instructions, the expected template, the student/team context, and the work itself. Metadata is useful triage evidence; it cannot establish how a student completed the assignment.
"""