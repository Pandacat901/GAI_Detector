# Define the AI Likelihood Scoring logic
def calculate_ai_likelihood(row):
    score = 0
    reasons = []

    # 1. Programmatic software signatures
    evidence_str = str(row.get('evidence', '')).lower()
    prog_tools = ['openpyxl', 'xlsxwriter', 'python-docx', 'python-pptx', 'pandas', 'gspread', 'reportlab', 'weasyprint', 'wkhtmltopdf']
    detected_prog = [tool for tool in prog_tools if tool in evidence_str]
    if detected_prog:
        score += 45
        reasons.append(f"Programmatic tool(s) detected: {', '.join(detected_prog)}")

    # 2. Direct AI footprint in metadata
    ai_tools = ['gpt', 'openai', 'claude', 'gemini', 'copilot']
    detected_ai = [ai for ai in ai_tools if ai in evidence_str]
    if detected_ai:
        score += 35
        reasons.append(f"AI keyword(s) detected: {', '.join(detected_ai)}")

    # 3. Missing standard metadata
    app = str(row.get('application', '')).strip()
    creator = str(row.get('creator', '')).strip()
    ext = str(row.get('extension', '')).lower()

    if ext in ['.xlsx', '.xlsm', '.docx', '.pptx']:
        if not app:
            score += 10
            reasons.append("Missing Application tag (common in raw scripts)")
        if not creator:
            score += 5
            reasons.append("Missing Creator name")

    # 4. Instant or non-human editing timestamps
    try:
        created = str(row.get('created', '')).strip()
        modified = str(row.get('modified', '')).strip()
        if created and modified and created == modified:
            score += 10
            reasons.append("Creation & modification times are identical (instant generation)")
    except:
        pass

    score = min(score, 100)
    return score, '; '.join(reasons) if reasons else 'Normal metadata footprints'

# Calculate scores
